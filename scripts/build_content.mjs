// Load the complete isolated content script through Chrome's manifest injection.
// Runtime module fetches are unnecessary and can fail independently of injection.
import './build_panel.mjs';
import {build} from '../browser-build/node_modules/esbuild/lib/main.js';
import {fileURLToPath} from 'node:url';
await build({
  entryPoints:[fileURLToPath(new URL('../extension/content-entry.js',import.meta.url))],
  outfile:fileURLToPath(new URL('../extension/content.js',import.meta.url)),
  bundle:true,platform:'browser',format:'iife',target:'chrome116',
  banner:{js:'// Generated by scripts/build_content.mjs. Edit content-entry.js and its modules.'},
});
await build({
  entryPoints:[fileURLToPath(new URL('../extension/source-bridge-entry.js',import.meta.url))],
  outfile:fileURLToPath(new URL('../extension/source-bridge.js',import.meta.url)),
  bundle:true,platform:'browser',format:'iife',target:'chrome116',
  banner:{js:'// Generated by scripts/build_content.mjs. Edit source-bridge-entry.js and its modules.'},
});
