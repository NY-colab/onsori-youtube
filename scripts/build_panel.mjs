// Generate a packaged UI template; no extension iframe or remote code.
import fs from 'node:fs/promises';
const ext=new URL('../extension/',import.meta.url);
const html=await fs.readFile(new URL('popup.html',ext),'utf8');
const css=await fs.readFile(new URL('popup.css',ext),'utf8');
const body=html.match(/<body>([\s\S]*?)<script/)[1];
const panelCss=css.replace(/html\[data-view=panel\] body/g,'PANELBODY').replace(/:root/g,':host').replace(/\bbody\b/g,'.panel-body').replace(/PANELBODY/g,'.panel-body');
await fs.writeFile(new URL('panel-template.js',ext),`// Generated by scripts/build_panel.mjs; edit popup.html / popup.css instead.\nexport const panelHTML=${JSON.stringify(body)};\nexport const panelCSS=${JSON.stringify(panelCss+'\n.panel-body{width:100%;max-height:none;overflow:visible;border:1px solid var(--line);border-radius:12px;}')};\n`);
