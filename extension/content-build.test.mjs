import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {build} from '../browser-build/node_modules/esbuild/lib/main.js';
import {fileURLToPath} from 'node:url';

test('manifest content bundle is current and needs no runtime module fetch',async()=>{
  const result=await build({entryPoints:[fileURLToPath(new URL('./content-entry.js',import.meta.url))],bundle:true,platform:'browser',format:'iife',target:'chrome116',write:false,metafile:true,banner:{js:'// Generated by scripts/build_content.mjs. Edit content-entry.js and its modules.'}});
  assert.equal(await readFile(new URL('./content.js',import.meta.url),'utf8'),result.outputFiles[0].text);
  assert.ok(Object.values(result.metafile.outputs).every(output=>output.imports.length===0));
  const manifest=JSON.parse(await readFile(new URL('./manifest.json',import.meta.url),'utf8'));
  assert.ok(manifest.content_scripts.some(entry=>entry.world!=='MAIN'&&entry.js.includes('content.js')));
});
